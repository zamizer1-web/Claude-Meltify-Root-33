#!/usr/bin/env python3
"""Generate the Root 33 plugin's adapter stubs from the design sheets.

The plugin (src/Root33.Plugin) implements the core's IBoardView and IBoardActions over Root's live game and calls the
core's IGameHooks from Harmony patches. Root's own code exists only on the creator's PC, so the PC session fills these
in one by one. This script writes the parts that follow from the sheets, so they never drift from them:

  src/Root33.Plugin/Adapter/RootBoard.cs   one member per board_reads / board_actions row that is not mapped yet; each
                                           throws NotMappedException with the row id and the row's engineSymbol guess
  src/Root33.Plugin/Adapter/EngineIds.cs   Root's own ids from the sheets' plugin columns: map_autumn.engineClearingId,
                                           engines.engineType ("unknown" until confirmed)
  src/Root33.Plugin/Patches/HookMap.cs     one commented placeholder per game_hooks row (id, when it fires, engineSymbol
                                           guess, patchKind) with the Harmony patch to write, and HookMap.Rows

Mapping a member: write it in src/Root33.Plugin/Adapter/RootBoard.Mapped.cs (or another hand-written file in Adapter/)
marked [Mapped("read.seats")], put the confirmed symbol in the sheet's engineSymbol cell and clear its _unverified entry,
then rerun this script: the stub disappears from RootBoard.cs. Patching a hook: write the patch class in Patches/ marked
[RootHook("hook.evening-end")] and rerun: HookMap.cs marks the row patched.

Usage: python3 -I tools/gen_plugin_stubs.py [--check]
  --check   write nothing; exit 1 when a generated file is out of date (CI and the PC build run it)
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHEETS = ROOT / "sheets"
PLUGIN = ROOT / "src" / "Root33.Plugin"
ADAPTER = PLUGIN / "Adapter"
PATCHES = PLUGIN / "Patches"
GENERATED = {
    ADAPTER / "RootBoard.cs",
    ADAPTER / "EngineIds.cs",
    PATCHES / "HookMap.cs",
}
HEADER = ("// <auto-generated>\n"
          "// Generated by tools/gen_plugin_stubs.py from sheets/*.json. Do not edit; change the sheet (or map the member in a\n"
          "// hand-written file) and run: python3 -I tools/gen_plugin_stubs.py\n"
          "// </auto-generated>\n")


def rows(sheet):
    return json.loads((SHEETS / f"{sheet}.json").read_text(encoding="utf-8"))["rows"]


def pascal(text):
    parts = [p for p in re.split(r"[^A-Za-z0-9]+", text) if p]
    return "".join(p[:1].upper() + p[1:] for p in parts)


def cs_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\n", "\\n") + '"'


def xml(s):
    return (s or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def comment_text(s, width=112, prefix="        // "):
    """Wrap text into // comment lines."""
    words, lines, line = (s or "").split(), [], ""
    for w in words:
        if line and len(line) + 1 + len(w) > width:
            lines.append(line)
            line = w
        else:
            line = (line + " " + w).strip()
    if line:
        lines.append(line)
    return "\n".join(prefix + l for l in lines) if lines else prefix.rstrip()


def strip_comments(code):
    """C# source without // and /* */ comments (string literals with // are not expected in these files)."""
    code = re.sub(r"/\*.*?\*/", "", code, flags=re.S)
    return "\n".join(line.split("//", 1)[0] for line in code.splitlines())


def marked(folder, attribute):
    """Row ids named by [attribute("id")] in the hand-written .cs files of a folder, with the file that names them."""
    found = {}
    if not folder.exists():
        return found
    for path in sorted(folder.glob("*.cs")):
        if path in GENERATED:
            continue
        for m in re.finditer(r"\[\s*" + attribute + r"\s*\(\s*\"([^\"]+)\"\s*\)\s*\]", strip_comments(path.read_text(encoding="utf-8"))):
            found.setdefault(m.group(1), path.name)
    return found


def split_params(params):
    """'SeatId seat, IReadOnlyList<EngineId> owned, Dictionary<K, V> d' -> [(type, name), ...] (commas inside <> kept)."""
    out, depth, cur = [], 0, ""
    for ch in params:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    result = []
    for p in out:
        t, n = p.rsplit(" ", 1)
        result.append((t.strip(), n.strip()))
    return result


SIG = re.compile(r"^\s*(?P<ret>.+?)\s+(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*\((?P<params>.*)\)\s*;?\s*$")


def parse_sig(sig):
    m = SIG.match(sig)
    if not m:
        raise SystemExit(f"cannot parse C# signature: {sig}")
    return m.group("ret"), m.group("name"), split_params(m.group("params"))


def unverified(row, column):
    return column in (row.get("_unverified") or {})


# ------------------------------------------------------------------------------------------------ RootBoard.cs

def root_board():
    reads, actions = rows("board_reads"), rows("board_actions")
    mapped = marked(ADAPTER, "Mapped")
    known = {r["id"] for r in reads} | {r["id"] for r in actions}
    for rid, f in mapped.items():
        if rid not in known:
            raise SystemExit(f"{f}: [Mapped(\"{rid}\")] names no board_reads or board_actions row")

    def stubs(sheet_rows, title):
        out = [f"        // ================================================================= {title}\n"]
        for r in sheet_rows:
            if r["id"] in mapped:
                out.append(f"        // {r['id']}: mapped in {mapped[r['id']]}\n")
                continue
            sig = r["csSignature"].strip().rstrip(";")
            guess = r.get("engineSymbol") or "unknown"
            note = " (unverified)" if unverified(r, "engineSymbol") else ""
            doc = [f"        /// <summary>{xml(r['id'])}: {xml(r['description'])}</summary>",
                   f"        /// <remarks>engineSymbol{note}: {xml(guess)}"]
            if r.get("fallback"):
                doc.append(f"        /// Fallback while unsupported: {xml(r['fallback'])}")
            doc[-1] += "</remarks>"
            out.append("\n".join(doc) + f"\n        public {sig} =>\n            throw new NotMappedException({cs_string(r['id'])}, {cs_string(guess)});\n")
        return "\n".join(out)

    def ids(name, sheet_rows, doc):
        left = [r["id"] for r in sheet_rows if r["id"] not in mapped]
        body = "".join(f"\n            {cs_string(i)}," for i in left)
        return f"        /// <summary>{doc}</summary>\n        public static readonly string[] {name} =\n        {{{body}\n        }};\n"

    n_reads = sum(1 for r in reads if r["id"] in mapped)
    n_actions = sum(1 for r in actions if r["id"] in mapped)
    return (HEADER + "#nullable enable\nusing System.Collections.Generic;\nusing Root33.Core;\n\nnamespace Root33.Plugin.Adapter\n{\n"
            "    /// <summary>\n"
            "    /// The core's view of Root's live game (IBoardView, one member per sheets/board_reads.json row) and the core's hands on it\n"
            "    /// (IBoardActions, one member per sheets/board_actions.json row). This generated part holds every row that is not mapped\n"
            "    /// yet: each throws <see cref=\"NotMappedException\"/> with the row id and the sheet's engineSymbol guess. Mapped members\n"
            "    /// live in RootBoard.Mapped.cs, marked [Mapped(\"row id\")]; rerun tools/gen_plugin_stubs.py after mapping one.\n"
            f"    /// Mapped so far: {n_reads}/{len(reads)} reads, {n_actions}/{len(actions)} actions.\n"
            "    /// </summary>\n"
            "    public sealed partial class RootBoard : IBoardView, IBoardActions\n    {\n"
            f"        public const int ReadRows = {len(reads)};\n"
            f"        public const int ActionRows = {len(actions)};\n\n"
            + ids("UnmappedReads", reads, "board_reads rows still stubbed here, in sheet order.") + "\n"
            + ids("UnmappedActions", actions, "board_actions rows still stubbed here, in sheet order (the core is told they are unsupported, so it takes their sheet fallbacks).") + "\n"
            + stubs(reads, "IBoardView (sheets/board_reads.json)") + "\n"
            + stubs(actions, "IBoardActions (sheets/board_actions.json)")
            + "    }\n}\n")


# ------------------------------------------------------------------------------------------------ EngineIds.cs

def engine_ids():
    clearings = rows("map_autumn")
    engines = rows("engines")
    clear_lines = []
    for r in sorted(clearings, key=lambda r: r["id"]):
        n = int(r["id"].split(".")[1])
        v = r.get("engineClearingId") or "unknown"
        state = "unverified" if unverified(r, "engineClearingId") else "confirmed"
        clear_lines.append(f"            [{n}] = {cs_string(v)},   // {r['id']} {r['continentName']} ({r['suit']}) - {state}")
    engine_lines = []
    for r in engines:
        v = r.get("engineType") or "unknown"
        state = "unverified" if unverified(r, "engineType") else "confirmed"
        engine_lines.append(f"            [{cs_string(r['id'])}] = {cs_string(v)},   // {r['rootName']} - {state}")
    return (HEADER + "#nullable enable\nusing System.Collections.Generic;\nusing Root33.Core;\n\nnamespace Root33.Plugin.Adapter\n{\n"
            "    /// <summary>\n"
            "    /// Root's own ids for what the sheets name, from their plugin columns: map_autumn.engineClearingId (Root's id for each\n"
            "    /// Autumn clearing; the core numbers them 1-12 as autumn.01-12) and engines.engineType (Root's class or id for each\n"
            "    /// faction). \"unknown\" until the PC session confirms them in Root's code and writes them into the sheets.\n"
            "    /// </summary>\n"
            "    public static class EngineIds\n    {\n"
            "        /// <summary>The core's Autumn clearing number -> Root's own clearing id.</summary>\n"
            "        public static readonly IReadOnlyDictionary<int, string> AutumnClearings = new Dictionary<int, string>\n        {\n"
            + "\n".join(clear_lines) + "\n        };\n\n"
            "        /// <summary>engines.json id -> Root's own type or id for that faction.</summary>\n"
            "        public static readonly IReadOnlyDictionary<string, string> EngineTypes = new Dictionary<string, string>\n        {\n"
            + "\n".join(engine_lines) + "\n        };\n\n"
            "        /// <summary>Whether every Autumn clearing's Root id is known.</summary>\n"
            "        public static bool AutumnClearingsKnown\n        {\n            get\n            {\n"
            "                foreach (var v in AutumnClearings.Values) if (v == \"unknown\") return false;\n                return true;\n            }\n        }\n\n"
            "        /// <summary>The core's clearing for Root's own Autumn clearing id, or null when that id is not in the sheet.</summary>\n"
            "        public static ClearingId? AutumnClearingFromRoot(string rootClearingId)\n        {\n"
            "            foreach (var kv in AutumnClearings) if (kv.Value != \"unknown\" && kv.Value == rootClearingId) return new ClearingId(kv.Key);\n"
            "            return null;\n        }\n\n"
            "        /// <summary>Root's own id for one of the core's Autumn clearings, or null while it is unknown.</summary>\n"
            "        public static string? RootIdOfAutumnClearing(ClearingId c) =>\n"
            "            AutumnClearings.TryGetValue(c.Value, out var v) && v != \"unknown\" ? v : null;\n"
            "    }\n}\n")


# ------------------------------------------------------------------------------------------------ HookMap.cs

def hook_map():
    hooks = rows("game_hooks")
    patched = marked(PATCHES, "RootHook")
    known = {r["id"] for r in hooks}
    for rid, f in patched.items():
        if rid not in known:
            raise SystemExit(f"{f}: [RootHook(\"{rid}\")] names no game_hooks row")
    entries, table = [], []
    for r in hooks:
        rid, kind = r["id"], r.get("patchKind") or "postfix"
        ret, name, params = parse_sig(r["csHandler"])
        guess = r.get("engineSymbol") or "unknown"
        flags = [c for c in ("engineSymbol", "patchKind") if unverified(r, c)]
        status = f"patched in {patched[rid]}" if rid in patched else ("no patch: " + guess.split(":", 1)[-1].strip() if kind == "event" else "not patched yet")
        args = ", ".join(n for _, n in params)
        call = f"g.{name}({args})"
        provides = r.get("provides") or []
        lines = [f"        // ===== {rid} · {kind} · {status}",
                 comment_text("When:  " + r["when"]),
                 f"        // Core:  {r['csHandler'].strip().rstrip(';')}",
                 f"        // Root:  {guess}" + (f"   ({' and '.join(flags)} unverified)" if flags else "")]
        if provides:
            lines.append(comment_text("Root provides: " + "; ".join(provides)))
        if kind == "event":
            lines.append("        // Nothing to patch in Root: " + ("the core raises it from hook.turn-end (Root33Runtime gets it like any other hook)."
                                                                       if rid == "hook.act-change" else
                                                                       "the mod's own overlay raises it: Root33Runtime.Hook(" + cs_string(rid) + ", g => " + call + ")."))
        else:
            cls = pascal(rid.split(".", 1)[1]) + "Patch"
            locals_ = [f"        //         var {n} = default({t}); // TODO from Root: {t} {n}" for t, n in params]
            lines += ["        //",
                      "        // [HarmonyPatch(typeof(TODO_RootType), nameof(TODO_RootType.TODO_Method))]",
                      f"        // [RootHook({cs_string(rid)})]",
                      f"        // internal static class {cls}",
                      "        // {"]
            if ret == "void":
                lines += [f"        //     private static void {'Prefix' if kind == 'prefix' else 'Postfix'}(/* TODO_RootType __instance, Root's arguments */)",
                          "        //     {"] + locals_ + [
                          f"        //         Root33Runtime.Hook({cs_string(rid)}, g => {call});",
                          "        //     }"]
            elif ret == "bool" and kind == "prefix":
                lines += ["        //     private static bool Prefix(ref bool __result /*, TODO_RootType __instance, Root's arguments */)",
                          "        //     {"] + locals_ + [
                          f"        //         if (Root33Runtime.Ask({cs_string(rid)}, g => {call}, true)) return true;",
                          "        //         __result = false;   // the core says no: skip Root's check and answer false",
                          "        //         return false;",
                          "        //     }"]
            elif ret == "bool":
                lines += ["        //     private static void Postfix(ref bool __result /*, TODO_RootType __instance, Root's arguments */)",
                          "        //     {"] + locals_ + [
                          f"        //         if (__result) __result = Root33Runtime.Ask({cs_string(rid)}, g => {call}, true);",
                          "        //     }"]
            elif ret.startswith("string") and kind == "prefix":
                lines += ["        //     private static bool Prefix(/* TODO_RootType __instance, Root's arguments */)",
                          "        //     {"] + locals_ + [
                          f"        //         var key = Root33Runtime.Ask<string?>({cs_string(rid)}, g => {call}, null);",
                          "        //         if (key == null) return true;   // Root's own AI decides",
                          "        //         // take the action `key` through the mapped do.submit-action, then skip Root's AI step",
                          "        //         return !Root33Runtime.Current!.Board.SubmitAction(seat, key);",
                          "        //     }"]
            else:
                lines += [f"        //     private static void Postfix(/* TODO_RootType __instance, Root's arguments */)",
                          "        //     {"] + locals_ + [
                          f"        //         var text = Root33Runtime.Ask({cs_string(rid)}, g => {call}, \"\");",
                          "        //         // store `text` beside Root's save, under the game's id (hook.load reads it back)",
                          "        //     }"]
            lines.append("        // }")
        entries.append("\n".join(lines))
        table.append(f"            new Row({cs_string(rid)}, {cs_string(r['csHandler'].strip().rstrip(';'))}, {cs_string(kind)}, "
                     f"{cs_string(guess)}, {'false' if flags else 'true'}, {cs_string(patched[rid]) if rid in patched else 'null'}),")
    n_patch = sum(1 for r in hooks if r.get("patchKind") != "event")
    n_done = sum(1 for r in hooks if r["id"] in patched)
    return (HEADER + "#nullable enable\n\nnamespace Root33.Plugin.Patches\n{\n"
            "    /// <summary>\n"
            "    /// Where Root 33 hooks into Root: one entry per sheets/game_hooks.json row with the moment it fires, the IGameHooks member\n"
            "    /// it calls, the sheet's guess at Root's method (engineSymbol) and the patch kind. Each row below has the Harmony patch to\n"
            "    /// write once Root's method is found (Root33.Discover's report.md, the F9 probe, UnityExplorer). The pattern:\n"
            "    /// <code>\n"
            "    /// [HarmonyPatch(typeof(Il2CppRoot.TurnController), nameof(Il2CppRoot.TurnController.EndEvening))]   // Root's method\n"
            "    /// [RootHook(\"hook.evening-end\")]                                                                  // the sheet row\n"
            "    /// internal static class EveningEndPatch\n"
            "    /// {\n"
            "    ///     private static void Postfix(Il2CppRoot.TurnController __instance) =>\n"
            "    ///         Root33Runtime.Hook(\"hook.evening-end\", g => g.OnEveningEnd(RootBoard.SeatOf(__instance.CurrentPlayer)));\n"
            "    /// }\n"
            "    /// </code>\n"
            "    /// Root33Runtime.Hook queues hooks the core raises while it runs and logs a core exception once per hook (the game goes\n"
            "    /// on); Root33Runtime.Ask answers questions (battle legality, bot decisions) with a fallback. Plugin.Load applies every\n"
            "    /// [HarmonyPatch] class in this assembly. Mark each patch [RootHook(\"row id\")] and rerun tools/gen_plugin_stubs.py.\n"
            f"    /// Patched so far: {n_done}/{n_patch} rows that need a patch ({len(hooks) - n_patch} are raised by the mod itself).\n"
            "    /// </summary>\n"
            "    public static class HookMap\n    {\n"
            "        /// <summary>One game_hooks row as the plugin sees it.</summary>\n"
            "        public sealed class Row\n        {\n"
            "            public Row(string id, string handler, string patchKind, string engineSymbol, bool verified, string? patchedIn)\n"
            "            {\n                Id = id; Handler = handler; PatchKind = patchKind; EngineSymbol = engineSymbol; Verified = verified; PatchedIn = patchedIn;\n            }\n"
            "            public string Id { get; }\n            public string Handler { get; }\n            public string PatchKind { get; }\n"
            "            public string EngineSymbol { get; }\n"
            "            /// <summary>engineSymbol and patchKind are confirmed in the sheet.</summary>\n"
            "            public bool Verified { get; }\n"
            "            /// <summary>The Patches/ file whose [RootHook] names this row, or null.</summary>\n"
            "            public string? PatchedIn { get; }\n"
            "            public bool NeedsPatch => PatchKind != \"event\";\n        }\n\n"
            f"        public static readonly Row[] Rows =\n        {{\n" + "\n".join(table) + "\n        };\n\n"
            + "\n\n".join(entries) + "\n    }\n}\n")


def main():
    ap = argparse.ArgumentParser(description="Generate the Root 33 plugin's adapter stubs from the sheets.")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when a generated file is out of date")
    args = ap.parse_args()
    outputs = {
        ADAPTER / "RootBoard.cs": root_board(),
        ADAPTER / "EngineIds.cs": engine_ids(),
        PATCHES / "HookMap.cs": hook_map(),
    }
    stale = []
    for path, text in outputs.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    rel = [str(p.relative_to(ROOT)) for p in stale]
    if args.check:
        if stale:
            print("Out of date (run python3 -I tools/gen_plugin_stubs.py): " + ", ".join(rel))
            return 1
        print("Plugin stubs are up to date.")
        return 0
    print(("Wrote " + ", ".join(rel)) if stale else "Plugin stubs were already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
